"""Codec for SPS Commerce RSX canonical XML (schema v7.7.0).

RSX is SPS's normalized document format: one ``Orders``/``Shipments``/
``Invoices`` schema covers every trading partner; SPS maps to each
partner's native EDI behind it. Namespace:
``http://www.spscommerce.com/RSX``.

Inbound payloads are parsed with ``xmltodict`` into plain dicts that keep
the RSX element names — the dict shape *is* the schema, so mapping code
reads the same vocabulary as the partner implementation guide
(``OrderLine.VendorPartNumber``, ``Header.Address``...). ``FORCE_LIST``
pins every ``[0..*]`` group to a list — xmltodict otherwise collapses a
single child element to a bare dict.

Outbound documents are generated by QWeb ``edi.exchange.template.output``
records (see ``edi_exchange_template_oca``); the codec is inbound-only.

Design doc: docs/EDI_SPSCOMMERCE.md
"""

import xmltodict

RSX_NS = "http://www.spscommerce.com/RSX"

DOC_ROOTS = {
    "orders": "Orders",
    "order_acks": "OrderAcks",
    "shipments": "Shipments",
    "invoices": "Invoices",
}

# Every group declared [0..*] in the 7.7.0 schemas is pinned to a list so
# mapping code never has to branch on "dict vs list".
FORCE_LIST = (
    # roots' document elements
    "Order",
    "OrderAck",
    "Shipment",
    "Invoice",
    # shared groups (all three documents)
    "AdditionalContactDetails",
    "AdditionalPOTypeCodes",
    "Address",
    "CarrierInformation",
    "CarrierSpecialHandlingDetail",
    "ChargesAllowances",
    "Commodity",
    "ConditionOfSale",
    "Contacts",
    "Dates",
    "FOBRelatedInstruction",
    "FloorReady",
    "ItemAttribute",
    "LeadTime",
    "LineItem",
    "LocationQuantity",
    "MarksAndNumbersCollection",
    "MasterItemAttribute",
    "Measurements",
    "MonetaryAmounts",
    "Notes",
    "Packaging",
    "PalletInformation",
    "Paperwork",
    "PaymentTerms",
    "PhysicalDetails",
    "PriceInformation",
    "ProductID",
    "ProductOrItemDescription",
    "QuantitiesSchedulesLocations",
    "QuantityAndWeight",
    "QuantityTotals",
    "References",
    "ReferenceIDs",
    "RegulatoryCompliances",
    "RestrictionsOrConditions",
    "SealNumbers",
    "ServiceLevelCodes",
    "Subline",
    "Taxes",
    # Shipments hierarchy
    "ContainerLevel",
    "ItemLevel",
    "OrderLevel",
    "PackLevel",
)


def parse(payload):
    """Parse an RSX payload into dicts (RSX namespace collapsed away).

    Returns a dict keyed by the root element name
    (``{"Orders": {...}}``). Raises ``ValueError`` on malformed XML.
    """
    if isinstance(payload, str):
        payload = payload.encode()
    try:
        return xmltodict.parse(
            payload,
            process_namespaces=True,
            # None collapses this namespace: RSX elements map to plain
            # names; anything foreign keeps its prefix and fails the
            # root check downstream instead of silently parsing.
            namespaces={RSX_NS: None},
            force_list=FORCE_LIST,
        )
    except xmltodict.expat.ExpatError as err:
        raise ValueError(f"Invalid XML payload: {err}") from err


def root_name(data):
    """Return the document root element name (e.g. ``Orders``)."""
    return next(iter(data), None)


def root_document(data):
    """Return the document key (orders/shipments/invoices) for parsed data."""
    name = root_name(data)
    return next((key for key, root in DOC_ROOTS.items() if root == name), None)


def parse_orders(payload):
    """Parse an <Orders> payload; returns a list of <Order> dicts."""
    data = parse(payload)
    if root_name(data) != "Orders":
        raise ValueError(f"Expected <Orders> root, got <{root_name(data)}>.")
    return (data["Orders"] or {}).get("Order") or []


def parse_order_acks(payload):
    """Parse an <OrderAcks> payload; returns a list of <OrderAck> dicts."""
    data = parse(payload)
    if root_name(data) != "OrderAcks":
        raise ValueError(f"Expected <OrderAcks> root, got <{root_name(data)}>.")
    return (data["OrderAcks"] or {}).get("OrderAck") or []


def serialize_orders(orders):
    """Serialize <Order> dict(s) back into an <Orders> XML payload.

    Used to split batched inbound files: each split exchange record
    carries a single-order document that re-enters the normal
    receive/process pipeline.
    """
    if isinstance(orders, dict):
        orders = [orders]
    return xmltodict.unparse(
        {"Orders": {"@xmlns": RSX_NS, "Order": orders}}, pretty=True
    ).encode()


def xsd_validate(payload, schema_path):
    """Validate an RSX payload against an XSD schema file.

    Returns a list of error strings; empty means valid. SPS publishes
    the 7.7.0 schemas but they are not shipped with the module — point
    ``rsx.xsd_path`` at a local copy to enable validation.
    """
    from lxml import etree

    if isinstance(payload, str):
        payload = payload.encode()
    schema = etree.XMLSchema(etree.parse(schema_path))
    doc = etree.fromstring(payload)
    if schema.validate(doc):
        return []
    return [str(error) for error in schema.error_log]
